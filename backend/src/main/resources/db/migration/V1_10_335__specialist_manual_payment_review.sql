CREATE TABLE specialist_manual_payment_reviews (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    order_id BIGINT NOT NULL,
    payment_link_id BIGINT NOT NULL,
    amount_kopecks BIGINT NOT NULL,
    recipient_profile_id BIGINT NOT NULL,
    recipient_user_id BIGINT NOT NULL,
    recipient_key VARCHAR(160) NOT NULL,
    requested_by_user_id BIGINT NOT NULL,
    requested_by VARCHAR(150) NOT NULL,
    reason VARCHAR(500) NOT NULL,
    receipt_url TEXT NULL,
    status VARCHAR(32) NOT NULL,
    requested_at DATETIME(6) NOT NULL,
    notified_at DATETIME(6) NULL,
    deadline_at DATETIME(6) NULL,
    disputed_at DATETIME(6) NULL,
    settled_at DATETIME(6) NULL,
    resolved_at DATETIME(6) NULL,
    resolved_by VARCHAR(150) NULL,
    resolution_note VARCHAR(500) NULL,
    resolution_kind VARCHAR(32) NULL,
    last_attempt_at DATETIME(6) NULL,
    last_error VARCHAR(512) NULL,
    attempt_count INT NOT NULL DEFAULT 0,
    CONSTRAINT uk_specialist_manual_payment_link UNIQUE (payment_link_id),
    INDEX idx_specialist_manual_payment_due (status, deadline_at, id),
    INDEX idx_specialist_manual_payment_order (order_id, status, id)
);
