export class CommonInvoiceGuideComponent implements AfterViewInit {
  /** Section to show first, for example the group whose «?» was pressed. */
  @Input() section: string = 'overview';
  /** Another manual may reuse the dialog: its own sections, title and one-line introduction. */
  @Input() sections: readonly GuideSectionContent[] = COMMON_INVOICE_GUIDE;
  @Input() heading = 'Работа с общим счётом';
  @Input() intro = 'Что означает каждый блок панели и когда нажимать каждую кнопку.';
  @Output() readonly closed = new EventEmitter<void>();
  @ViewChild('closeButton') private closeButton?: ElementRef<HTMLButtonElement>;
  @ViewChild('body') private body?: ElementRef<HTMLElement>;

  ngAfterViewInit(): void {
    this.closeButton?.nativeElement.focus({ preventScroll: true });
    if (this.section !== 'overview') {
      this.scrollTo(this.section, false);
    }
  }

  anchor(id: string): string {
    return `common-invoice-guide-${id}`;
  }

  scrollTo(id: string, smooth = true): void {
    this.section = id;
    const body = this.body?.nativeElement;
    const target = body?.querySelector<HTMLElement>(`#${this.anchor(id)}`);
    if (!body || !target) {
      return;
    }
    const top = Math.max(0, target.offsetTop - body.offsetTop);
    if (typeof body.scrollTo === 'function') {
      // 'instant' overrides the container's smooth scrolling when the guide opens on a section.
      body.scrollTo({ top, behavior: smooth ? 'smooth' : 'instant' });
    } else {
      body.scrollTop = top;
    }
  }
}
